-- ---------------------------------------------------------------------------
-- Broker listings
-- ---------------------------------------------------------------------------
create table public.broker_listings (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null unique references public.organizations(id) on delete cascade,
  about text check (about is null or char_length(about) <= 500),
  years_in_business smallint check (years_in_business is null or years_in_business between 0 and 200),
  team_size integer check (team_size is null or team_size between 0 and 100000),
  merchandisers integer check (merchandisers is null or merchandisers between 0 and 100000),
  channels integer[] not null default '{}',
  distributors integer[] not null default '{}',
  categories integer[] not null default '{}',
  conflicts integer[] not null default '{}',
  current_lines text check (current_lines is null or char_length(current_lines) <= 2000),
  commission_model public.commission_model,
  rate_low numeric(5,2) check (rate_low is null or rate_low between 0 and 100),
  rate_high numeric(5,2) check (rate_high is null or rate_high between 0 and 100),
  retainer numeric(10,2) check (retainer is null or retainer >= 0),
  min_term_months smallint check (min_term_months is null or min_term_months between 0 and 120),
  -- Lifecycle. Brokers move draft -> submitted via submit_listing();
  -- live/paused is set only by sync_listing_status() (webhook or admin).
  status public.listing_status not null default 'draft',
  admin_paused boolean not null default false,
  admin_pause_reason text,
  not_taking_new_lines boolean not null default false,
  away_message text check (away_message is null or char_length(away_message) <= 1000),
  completeness smallint not null default 0 check (completeness between 0 and 100),
  verified_at timestamptz,               -- set only by admin verification
  submitted_at timestamptz,
  live_since timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint listing_rate_order check (rate_low is null or rate_high is null or rate_low <= rate_high)
);

-- Public contact lives apart from the listing so that brands can only get it
-- through reveal_contact(), which logs the reveal and enforces the daily cap.
create table public.broker_contacts (
  listing_id uuid primary key references public.broker_listings(id) on delete cascade,
  name text check (name is null or char_length(name) <= 120),
  title text check (title is null or char_length(title) <= 120),
  email text check (email is null or email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  phone text check (phone is null or char_length(phone) <= 40),
  updated_at timestamptz not null default now()
);

create table public.broker_states (
  listing_id uuid not null references public.broker_listings(id) on delete cascade,
  state_code char(2) not null references public.states(code),
  primary key (listing_id, state_code)
);
create index broker_states_state on public.broker_states (state_code);

create table public.broker_retailers (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.broker_listings(id) on delete cascade,
  retailer_id integer references public.retailers(id),
  custom_name text check (custom_name is null or char_length(custom_name) between 1 and 120),
  call_frequency public.call_frequency not null,
  created_at timestamptz not null default now(),
  constraint broker_retailers_one_kind check ((retailer_id is null) <> (custom_name is null))
);
create unique index broker_retailers_ref on public.broker_retailers (listing_id, retailer_id) where retailer_id is not null;
create unique index broker_retailers_custom on public.broker_retailers (listing_id, lower(custom_name)) where custom_name is not null;
create index broker_retailers_retailer on public.broker_retailers (retailer_id);

create table public.broker_references (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.broker_listings(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120),
  brand text not null check (char_length(brand) between 1 and 120),
  email text check (email is null or email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  phone text check (phone is null or char_length(phone) <= 40),
  status public.reference_status not null default 'pending',
  admin_notes text,
  created_at timestamptz not null default now()
);
create index broker_references_listing on public.broker_references (listing_id);

create table public.listing_documents (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.broker_listings(id) on delete cascade,
  storage_path text not null unique,
  file_name text not null check (char_length(file_name) between 1 and 200),
  mime_type text not null check (mime_type = 'application/pdf'),
  size_bytes integer not null check (size_bytes between 1 and 10485760),
  is_private boolean not null default false,
  created_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.verifications (
  id uuid primary key default gen_random_uuid(),
  listing_id uuid not null references public.broker_listings(id) on delete cascade,
  status public.verification_status not null default 'requested',
  requested_by uuid references public.users(id) on delete set null,
  checked_by uuid references public.users(id) on delete set null,
  reason text,                           -- sent to the broker on reject/revoke
  decided_at timestamptz,
  created_at timestamptz not null default now()
);
create index verifications_listing on public.verifications (listing_id, created_at desc);
-- Only one open request per listing.
create unique index verifications_one_open on public.verifications (listing_id) where status = 'requested';

-- Purvey's working notes and checklist for a verification. Admin-only.
create table public.verification_reviews (
  verification_id uuid primary key references public.verifications(id) on delete cascade,
  references_reached boolean not null default false,
  retailers_confirmed boolean not null default false,
  notes text,
  updated_by uuid references public.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table public.subscriptions (
  org_id uuid primary key references public.organizations(id) on delete cascade,
  stripe_customer_id text unique,
  stripe_subscription_id text unique,
  status text,                           -- Stripe status, e.g. active, past_due, canceled
  current_period_end timestamptz,
  cancel_at_period_end boolean not null default false,
  past_due_since timestamptz,
  comped boolean not null default false, -- admin comp: listed free
  updated_at timestamptz not null default now()
