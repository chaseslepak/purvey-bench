create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  brand_org_id uuid not null references public.organizations(id) on delete cascade,
  broker_org_id uuid not null references public.organizations(id) on delete cascade,
  brief_id uuid references public.briefs(id) on delete set null,
  -- One-time snapshot of the attached brief. The broker sees this, never the brief.
  brief_summary jsonb,
  started_by uuid not null references public.users(id),
  declined_at timestamptz,
  decline_reason public.decline_reason,
  decline_note text check (decline_note is null or char_length(decline_note) <= 1000),
  reported_at timestamptz,               -- gates admin read access
  last_message_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint conversations_distinct_orgs check (brand_org_id <> broker_org_id)
);
create index conversations_brand on public.conversations (brand_org_id, last_message_at desc);
create index conversations_broker on public.conversations (broker_org_id, last_message_at desc);

-- Each side's private view of a thread: stage, archive, mute, assignee.
-- Split out so the other side can never read it.
create table public.conversation_sides (
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  org_id uuid not null references public.organizations(id) on delete cascade,
  brand_stage public.brand_stage,
  broker_stage public.broker_stage,
  archived boolean not null default false,
  muted boolean not null default false,
  marked_unread boolean not null default false,
  assignee_user_id uuid references public.users(id) on delete set null,
  last_read_at timestamptz,
  primary key (conversation_id, org_id),
  constraint conversation_sides_one_stage check ((brand_stage is null) <> (broker_stage is null))
);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_user_id uuid references public.users(id) on delete set null,
  sender_org_id uuid not null references public.organizations(id) on delete cascade,
  -- Plain text only. Rendered as text with linkified URLs; never as HTML.
  body text not null check (char_length(body) between 1 and 10000),
  attachments jsonb not null default '[]',
  is_auto_reply boolean not null default false,
  read_at timestamptz,                   -- when the other side first read it
  created_at timestamptz not null default now()
);
create index messages_conversation on public.messages (conversation_id, created_at);

create table public.conversation_notes (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  org_id uuid not null references public.organizations(id) on delete cascade,
  author_user_id uuid references public.users(id) on delete set null,
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);
create index conversation_notes_conv on public.conversation_notes (conversation_id, org_id);

create table public.message_templates (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  body text not null check (char_length(body) between 1 and 10000),
  created_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.org_blocks (
  blocker_org_id uuid not null references public.organizations(id) on delete cascade,
  blocked_org_id uuid not null references public.organizations(id) on delete cascade,
  created_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (blocker_org_id, blocked_org_id)
);

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_user_id uuid references public.users(id) on delete set null,
  reporter_org_id uuid references public.organizations(id) on delete set null,
  conversation_id uuid references public.conversations(id) on delete cascade,
  listing_id uuid references public.broker_listings(id) on delete cascade,
  reason text not null check (char_length(reason) between 1 and 2000),
  status public.report_status not null default 'open',
  resolution text,
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  constraint reports_target check ((conversation_id is null) <> (listing_id is null))
