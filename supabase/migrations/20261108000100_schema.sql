-- ---------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------
create type public.org_type as enum ('brand', 'broker');
create type public.member_role as enum ('owner', 'member');
create type public.listing_status as enum ('draft', 'submitted', 'live', 'paused');
create type public.call_frequency as enum ('weekly', 'monthly', 'occasional');
create type public.commission_model as enum ('pct_net_sales', 'retainer_plus_pct', 'retainer_only');
create type public.verification_status as enum ('requested', 'verified', 'rejected', 'revoked');
create type public.reference_status as enum ('pending', 'reached', 'confirmed', 'unreachable');
create type public.brand_stage as enum ('contacted', 'talking', 'agreement_sent', 'signed', 'passed');
create type public.broker_stage as enum ('new', 'replied', 'in_discussion', 'won', 'lost', 'declined');
create type public.decline_reason as enum ('not_a_fit', 'category_conflict', 'not_taking_new_lines', 'other');
create type public.email_frequency as enum ('instant', 'daily', 'off');
create type public.profile_event_type as enum ('search_impression', 'profile_view', 'contact_reveal', 'save', 'message');
create type public.placement_status as enum ('new', 'contacted', 'quoted', 'won', 'lost');
create type public.report_status as enum ('open', 'resolved', 'dismissed');

-- ---------------------------------------------------------------------------
-- Reference lists (admin-managed)
