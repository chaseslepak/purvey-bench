create table public.regions (
  code text primary key,                 -- 'northeast', 'southeast', ...
  name text not null unique,
  sort smallint not null default 0
);

create table public.states (
  code char(2) primary key,
  name text not null unique,
  region_code text not null references public.regions(code)
);

create table public.retailers (
  id integer generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  active boolean not null default true,
  merged_into integer references public.retailers(id),
  created_at timestamptz not null default now()
);
create unique index retailers_name_lower on public.retailers (lower(name));

create table public.categories (
  id integer generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  active boolean not null default true,
  merged_into integer references public.categories(id),
  created_at timestamptz not null default now()
);
create unique index categories_name_lower on public.categories (lower(name));

create table public.channels (
  id integer generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  active boolean not null default true,
  merged_into integer references public.channels(id),
  created_at timestamptz not null default now()
);
create unique index channels_name_lower on public.channels (lower(name));

create table public.distributors (
  id integer generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  active boolean not null default true,
  merged_into integer references public.distributors(id),
  created_at timestamptz not null default now()
);
create unique index distributors_name_lower on public.distributors (lower(name));

-- ---------------------------------------------------------------------------
-- People and organizations
-- ---------------------------------------------------------------------------
create table public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text,
  phone text,
  role public.org_type,                  -- brand or broker; null until onboarding
  is_admin boolean not null default false,
  suspended_at timestamptz,
  created_at timestamptz not null default now(),
  constraint users_name_len check (name is null or char_length(name) <= 120),
  constraint users_phone_len check (phone is null or char_length(phone) <= 40)
);
create index users_email_lower on public.users (lower(email));

create table public.organizations (
  id uuid primary key default gen_random_uuid(),
  type public.org_type not null,
  name text not null check (char_length(name) between 1 and 120),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  logo_url text,
  website text check (website is null or website ~* '^https?://'),
  hq_city text check (hq_city is null or char_length(hq_city) <= 80),
  hq_state char(2) references public.states(code),
  suspended_at timestamptz,
  created_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.org_members (
  org_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references public.users(id) on delete cascade,
  role public.member_role not null default 'member',
  invited_by uuid references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (org_id, user_id),
  -- Every person belongs to exactly one organization.
  constraint org_members_one_org unique (user_id)
);

create table public.org_invites (
  id uuid primary key default gen_random_uuid(),
  org_id uuid not null references public.organizations(id) on delete cascade,
  email text not null check (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  role public.member_role not null default 'member',
  token_hash text not null unique,       -- sha256 of the emailed token
  invited_by uuid references public.users(id) on delete set null,
  accepted_at timestamptz,
  accepted_by uuid references public.users(id) on delete set null,
  expires_at timestamptz not null default now() + interval '14 days',
  created_at timestamptz not null default now()
);
create index org_invites_org on public.org_invites (org_id);

